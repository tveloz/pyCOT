"""
dependency.py — The dependency DAG among fragile circuits (Sec 2.8,
Def 2.20-2.22, Prop 2.22) and the irrRAF / indecomposable-sub-RAF
correspondence (Sec 5, Theorems 5.4-5.6).

Reuses Decomposition_Theorem's decomp engine (via decomp_shim) for the
one LP-backed primitive this needs: OP(F0 u Y), the set of species
overproducible in the sub-network generated by food together with a
growing set of circuits. Everything else here (interface, the Yt
fixpoint, depth, the >- relation) is pure set/graph logic on top of that.
"""
